#!/usr/bin/env node
/**
 * Builds every shard of the site (see scripts/shards.mjs and worker/router.js):
 *   1. plan the shards, write the search, near-me and vendor files and the indexable stops;
 *   2. `astro build` once per shard with SHARD set, into dist/<shard>, one at a time;
 *   3. strip from each shard what another one serves (public/ is copied into every build);
 *   4. move every shard's sitemap into main under one sitemap index, and copy every shard's
 *      scripts (_a/<shard>/) and all map data (geo/) into main;
 *   5. check every page (scripts/verify-build.mjs) and write the Workers configs.
 * `--deploy` deploys each shard as soon as it is built and checked, then deletes it: the whole
 * site is ~6.5 GB of HTML, more than the disk may have free. Main goes last.
 * `--server` deploys to our own server over SSH instead (scripts/deploy-server.mjs): each shard
 * goes into one new release there as it is built, and the release goes live after main.
 * `node scripts/build-all.mjs s3` rebuilds one shard (after a full build), then main, which
 * must carry that shard's new scripts.
 *
 * Why scripts and maps live in main: main's files are served without the router Worker
 * running, and static asset requests are free and unlimited, while every Worker run counts
 * toward the plan's daily request limit (100,000 a day on Workers Free; over it, the site
 * shows Cloudflare error 1027 until midnight UTC). Only page loads need the router.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { startRelease, syncShard, finishRelease } from './deploy-server.mjs';

const args = process.argv.slice(2);
const DEPLOY = args.includes('--deploy');
const SERVER = args.includes('--server');
const only = args.find((a) => !a.startsWith('--'));
const run = (cmd, args2, env = {}) => execFileSync(cmd, args2, { stdio: 'inherit', env: { ...process.env, ...env } });

if (!only) {
  run('node', ['scripts/vendor.mjs']);
  run('node', ['--max-old-space-size=8192', 'scripts/shards.mjs']);
  run('node', ['--max-old-space-size=8192', 'scripts/search-index.mjs']);
  run('node', ['--max-old-space-size=8192', 'scripts/indexed-stops.mjs']);
}
const plan = JSON.parse(fs.readFileSync('src/data/shards.json', 'utf8'));
// Main last: it carries the sitemap index for every shard, and the router binds to them all.
const SHARDS = only ? [...new Set([only, 'main'])] : [...plan.shards, 'main'];
const STAGE = 'data/sitemaps'; // shard sitemaps wait here until main is built
const SCRIPTS = 'data/shard-assets'; // and their scripts, as <shard>/_a/<shard>/...
if (!only) for (const d of [STAGE, SCRIPTS]) fs.rmSync(d, { recursive: true, force: true });
fs.mkdirSync(STAGE, { recursive: true });
fs.mkdirSync(SCRIPTS, { recursive: true });

function build(shard) {
  fs.rmSync(`dist/${shard}`, { recursive: true, force: true });
  const t0 = Date.now();
  run('npx', ['astro', 'build', '--silent'], { SHARD: shard, NODE_OPTIONS: '--max-old-space-size=6144' });
  console.log(`built ${shard} in ${Math.round((Date.now() - t0) / 1000)} s`);
}

/** Delete everything under dir for which keep(relative path) is false; drop empty folders. */
function prune(dir, keep) {
  let removed = 0;
  (function walk(d) {
    for (const f of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, f.name);
      const rel = path.relative(dir, p);
      if (f.isDirectory()) { walk(p); if (!fs.readdirSync(p).length) fs.rmdirSync(p); } else if (!keep(rel)) { fs.rmSync(p); removed++; }
    }
  })(dir);
  return removed;
}

function count(dir) {
  let n = 0;
  (function walk(d) { for (const f of fs.readdirSync(d, { withFileTypes: true })) f.isDirectory() ? walk(path.join(d, f.name)) : n++; })(dir);
  return n;
}

/** Free space on the disk holding the project, in GB: the whole site is ~6.5 GB of HTML. */
function freeGB() {
  const out = execFileSync('df', ['-k', '.']).toString().trim().split('\n').at(-1).split(/\s+/);
  return Number(out[3]) / 1024 / 1024;
}

const systemsOf = (shard) => Object.entries(plan.systems).filter(([, s]) => s === shard).map(([k]) => k);
const stopSystemsOf = (shard) => Object.entries(plan.split).filter(([, list]) => list.includes(shard)).map(([k]) => k);

// Workers configs: one assets-only Worker per shard, and the router with a binding to each.
fs.mkdirSync('wrangler', { recursive: true });
for (const shard of plan.shards) {
  fs.writeFileSync(`wrangler/${shard}.jsonc`, JSON.stringify({
    name: `stopwatch-${shard}`,
    compatibility_date: '2026-09-15',
    workers_dev: false,
    preview_urls: false,
    assets: { directory: `../dist/${shard}`, not_found_handling: '404-page' },
  }, null, 2));
}
/** The router's config, written once main is built: `geoInMain` is whether main has room for the maps. */
function writeRouterConfig(geoInMain) {
  fs.writeFileSync('wrangler.jsonc', `// Generated by scripts/build-all.mjs; edit the script, not this file.\n${JSON.stringify({
    name: 'transit-timetables',
    main: 'worker/router.js',
    compatibility_date: '2026-09-15',
    // Browsers' navigations to a path main has no file for get main's 404 page straight away,
    // without the Worker ever running, so the router must run first for every shard's pages.
    // Scripts (/_a/) are in main, and so are the maps (/geo/) when they fit: those never run it.
    assets: {
      directory: './dist/main', binding: 'ASSETS', not_found_handling: '404-page',
      run_worker_first: [...[...new Set(Object.keys(plan.systems).map((k) => k.split('/')[0]))].map((cc) => `/${cc}/*`), ...(geoInMain ? [] : ['/geo/*']), '/bc', '/bc/*', '/search.json'],
    },
    services: plan.shards.map((sh) => ({ binding: sh.toUpperCase(), service: `stopwatch-${sh}` })),
    routes: [{ pattern: 'transit.shivrajsinh.in', custom_domain: true }],
  }, null, 2)}\n`);
}

// Opened before the first build, so a wrong server setting fails in seconds, not after an hour.
const release = SERVER ? startRelease({ partial: Boolean(only) }) : null;
let total = 0;
for (const shard of SHARDS) {
  if (freeGB() < 2) throw new Error(`only ${freeGB().toFixed(1)} GB free: a shard needs about 1.5 GB while it is built`);
  build(shard);
  const dir = `dist/${shard}`;
  if (shard === 'main') {
    // Every shard's scripts, under their own names, so its pages load them from main.
    for (const sh of fs.readdirSync(SCRIPTS)) fs.cpSync(path.join(SCRIPTS, sh), dir, { recursive: true });
    // All map data is in public/geo and so already in this build; drop it only if it does not fit.
    const geoInMain = count(dir) <= 19_000;
    if (!geoInMain) {
      prune(dir, (rel) => !rel.startsWith('geo/'));
      console.log('main: no room for the map data, the router serves /geo/ from the shards');
    }
    writeRouterConfig(geoInMain);
    // One sitemap index over main's sitemap and every shard's, regrouped by page type
    // (scripts/sitemaps.mjs): core pages first, stop pages after.
    fs.mkdirSync(`${dir}/sitemaps`, { recursive: true });
    for (const f of fs.readdirSync(STAGE)) fs.copyFileSync(path.join(STAGE, f), `${dir}/sitemaps/${f}`);
    run('node', ['scripts/sitemaps.mjs', dir]);
  } else {
    fs.rmSync(path.join(SCRIPTS, shard), { recursive: true, force: true });
    if (fs.existsSync(`${dir}/_a/${shard}`)) fs.cpSync(`${dir}/_a/${shard}`, path.join(SCRIPTS, shard, '_a', shard), { recursive: true });
    for (const f of fs.readdirSync(dir)) {
      const m = /^sitemap-(\d+)\.xml$/.exec(f);
      if (m) fs.renameSync(path.join(dir, f), path.join(STAGE, `${shard}-${m[1]}.xml`));
    }
    const own = systemsOf(shard);
    const stopsOnly = stopSystemsOf(shard);
    const removed = prune(dir, (rel) => {
      if (rel === '404.html' || rel === '_headers') return true;
      if (rel.startsWith(`_a/${shard}/`)) return true;
      for (const key of own) if (rel === `${key}.html` || rel.startsWith(`${key}/`) || rel === `geo/${key}.json` || rel.startsWith(`geo/${key}/`)) return true;
      for (const key of stopsOnly) if (rel.startsWith(`${key}/stop/`)) return true;
      return false;
    });
    console.log(`pruned ${removed} files from ${shard}`);
  }
  const n = count(dir);
  total += n;
  if (n > 19_500) throw new Error(`${shard} has ${n} files, over the Workers limit`);
  console.log(`${shard}: ${n} files`);
  run('node', ['scripts/verify-build.mjs', dir]);
  if (SERVER) {
    syncShard(release, dir);
    if (shard === 'main') finishRelease(release);
    else fs.rmSync(dir, { recursive: true, force: true });
  } else if (DEPLOY) {
    if (shard === 'main') run('npx', ['wrangler', 'deploy']);
    else run('npx', ['wrangler', 'deploy', '-c', `wrangler/${shard}.jsonc`]);
    // Deployed: the disk is needed for the next shard.
    if (shard !== 'main') fs.rmSync(dir, { recursive: true, force: true });
  }
}
console.log(`${total} files in ${SHARDS.length} deployment${SHARDS.length === 1 ? '' : 's'}${DEPLOY || SERVER ? ', all deployed' : ''}`);
