#!/usr/bin/env node
/** Generates the exact Stopwatch-to-Headway redirects and the Googlebot exceptions they need. */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const HEADWAY = process.env.HEADWAY_DIR || path.join(os.homedir(), 'headway');
const site = JSON.parse(fs.readFileSync(path.join(HEADWAY, 'src/data/site.json'), 'utf8'));
const urls = [...new Set(site.pages.map((p) => p.url))].sort();
if (!urls.length || urls.some((url) => !/^\/[a-z]{2}\/[a-z0-9-]+\//.test(url))) throw new Error('Headway page list is empty or invalid');

const target = 'https://headway.shivrajsinh.in';
const map = `# Generated by scripts/headway-migration.mjs from ${HEADWAY}/src/data/site.json.\n${urls.map((url) => `location = ${url} { add_header X-Robots-Tag "index, follow" always; return 301 ${target}${url}$is_args$args; }`).join('\n')}\n`;
fs.writeFileSync(path.join(ROOT, 'deploy/headway-moved.conf'), map);

const robotsPath = path.join(ROOT, 'public/robots.txt');
const robots = fs.readFileSync(robotsPath, 'utf8');
const begin = '# BEGIN HEADWAY MIGRATION';
const end = '# END HEADWAY MIGRATION';
const block = `${begin}\n${urls.map((url) => `Allow: ${url}`).join('\n')}\n${end}`;
const existing = /# BEGIN HEADWAY MIGRATION[\s\S]*?# END HEADWAY MIGRATION/;
const anchor = /(User-agent: Googlebot\nDisallow: \/\n)/;
if (existing.test(robots)) fs.writeFileSync(robotsPath, robots.replace(existing, block));
else if (anchor.test(robots)) fs.writeFileSync(robotsPath, robots.replace(anchor, `$1${block}\n`));
// Googlebot may crawl the whole site, so the 301s are seen without per-URL robots exceptions.
else console.log('robots.txt allows Googlebot everywhere; no exceptions needed');

console.log(`${urls.length} exact Headway redirects and robots exceptions generated`);
