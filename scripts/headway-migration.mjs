#!/usr/bin/env node
/** Generates the Google-only noindex list for pages that also live on Headway and the Googlebot exceptions they need. */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const HEADWAY = process.env.HEADWAY_DIR || path.join(os.homedir(), 'headway');
const site = JSON.parse(fs.readFileSync(path.join(HEADWAY, 'src/data/site.json'), 'utf8'));
const all = [...new Set(site.pages.map((p) => p.url))].sort();
if (!all.length || all.some((url) => !/^\/[a-z]{2}\/[a-z0-9-]+\//.test(url))) throw new Error('Headway page list is empty or invalid');
// Australia is Stopwatch's own market again (relaunch on stopwatchtimetables.com, Nov 2026): its
// Australian pages stay indexable here and Headway's copies are the ones marked noindex
// (headway src/lib/site.js STOPWATCH_OWNS). Only Headway's other countries keep the Google-only noindex here.
const STOPWATCH_OWNS = (process.env.STOPWATCH_OWNS || 'au').split(',').map((c) => c.trim()).filter(Boolean);
const urls = all.filter((url) => !STOPWATCH_OWNS.includes(url.split('/')[1]));

// Visitors stay on Stopwatch (its pages earn more per visit than the new sites'): each moved page is
// still served here, with a noindex for Googlebot only, so Google keeps the copy on the new site and
// Bing and the AI assistants keep sending people to this one. deploy/nginx.conf reads these lines
// into `map $uri $stopwatch_google_noindex`.
const map = `# Generated by scripts/headway-migration.mjs from ${HEADWAY}/src/data/site.json.\n${urls.map((url) => `${url} "googlebot: noindex";`).join('\n')}\n`;
fs.writeFileSync(path.join(ROOT, 'deploy/headway-moved.conf'), map);

console.log(`${urls.length} Headway pages marked googlebot: noindex here (${all.length - urls.length} left indexable: ${STOPWATCH_OWNS.join(', ')})`);
