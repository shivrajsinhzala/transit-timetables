#!/usr/bin/env node
/** Generates Google-only noindex list for pages that also live on BusClock and the Googlebot exceptions they need. */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const BUSCLOCK = process.env.BUSCLOCK_DIR || path.join(os.homedir(), 'busclock');
const site = JSON.parse(fs.readFileSync(path.join(BUSCLOCK, 'src/data/site.json'), 'utf8'));
const urls = [...new Set([
  ...site.pages.map((p) => p.url),
  ...Object.values(site.systems).map((s) => s.url),
  '/ie', '/uk', '/ca',
])].sort();
if (!urls.length || urls.some((url) => !/^\/(ie|uk|ca)(\/[a-z0-9-]+(\/|$)|$)/.test(url))) throw new Error('BusClock page list is empty or invalid');

const target = 'https://busclock.shivrajsinh.in';
// Visitors stay on Stopwatch (its pages earn more per visit than the new sites'): each moved page is
// still served here, with a noindex for Googlebot only, so Google keeps the copy on the new site and
// Bing and the AI assistants keep sending people to this one. deploy/nginx.conf reads these lines
// into `map $uri $stopwatch_google_noindex`.
const map = `# Generated by scripts/busclock-migration.mjs from ${BUSCLOCK}/src/data/site.json.\n${urls.map((url) => `${url} "googlebot: noindex";`).join('\n')}\n`;
fs.writeFileSync(path.join(ROOT, 'deploy/busclock-moved.conf'), map);

const robotsPath = path.join(ROOT, 'public/robots.txt');
const robots = fs.readFileSync(robotsPath, 'utf8');
const begin = '# BEGIN BUSCLOCK MIGRATION';
const end = '# END BUSCLOCK MIGRATION';
const block = `${begin}\n${urls.map((url) => `Allow: ${url}`).join('\n')}\n${end}`;
const existing = /# BEGIN BUSCLOCK MIGRATION[\s\S]*?# END BUSCLOCK MIGRATION/;
const anchor = /(User-agent: Googlebot\nDisallow: \/\n)/;
let robotsNote = 'robots.txt already allows Googlebot';
if (existing.test(robots)) {
  fs.writeFileSync(robotsPath, robots.replace(existing, block));
  robotsNote = 'robots.txt exceptions updated';
} else if (anchor.test(robots)) {
  fs.writeFileSync(robotsPath, robots.replace(anchor, `$1${block}\n`));
  robotsNote = 'robots.txt exceptions added';
}

console.log(`${urls.length} exact BusClock redirects generated; ${robotsNote}`);
