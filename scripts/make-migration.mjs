#!/usr/bin/env node
/**
 * Writes the nginx pieces that decide which hosts serve Stopwatch, from src/lib/site.js:
 *
 *   deploy/stopwatch-hosts.conf     server_name of the main server block (deploy/nginx.conf)
 *   deploy/stopwatch-old-host.conf  the www and old-host server blocks, included by deploy/nginx.conf
 *
 * Each host has its own block because each has its own Cloudflare Origin CA certificate (one
 * zone each); all of them include deploy/stopwatch-site.conf, the site itself.
 *
 * MIGRATION_REDIRECTS=off (default): the new host serves the site, and the old host serves the
 * same files from its own block with its existing certificate, so nothing changes for anyone
 * until the switch. Pages already name SITE_URL as canonical either way.
 *
 * MIGRATION_REDIRECTS=on: every request to the old host, any path and query, is a 301 to the same
 * path and query on SITE_URL: never to the homepage. That includes /sitemap*, /robots.txt and
 * /llms*.txt. The one exception is /sw.js: browsers do not follow a redirect when they update a
 * service worker, so a 301 there would leave installed users on the old worker for good. The old
 * host serves a last worker instead that clears its caches, unregisters itself and reloads its
 * tabs, which then follow the 301 like any other request.
 *
 * www.<host> always 301s to the bare host.
 *
 *   MIGRATION_REDIRECTS=on node scripts/make-migration.mjs
 *
 * Then copy both files to /etc/nginx/snippets/ and reload nginx (deploy/README.md, "Moving to
 * stopwatchtimetables.com").
 */
import fs from 'node:fs';
import { SITE, SITE_HOST, OLD_HOSTS, MIGRATION_REDIRECTS } from '../src/lib/site.js';

const bare = SITE_HOST.replace(/^www\./, '');
// The new host's certificate is named in deploy/nginx.conf; the old host keeps the one it has.
const CERT = process.env.SSL_CERT || '/etc/ssl/stopwatchtimetables.pem';
const KEY = process.env.SSL_KEY || '/etc/ssl/stopwatchtimetables.key';
const OLD_CERT = process.env.OLD_SSL_CERT || '/etc/ssl/stopwatch.pem';
const OLD_KEY = process.env.OLD_SSL_KEY || '/etc/ssl/stopwatch.key';

// The last service worker for the old host (one line: nginx returns it as the body).
const killSw = [
  "self.addEventListener('install',()=>self.skipWaiting());",
  "self.addEventListener('activate',(e)=>e.waitUntil((async()=>{",
  'for(const k of await caches.keys())await caches.delete(k);',
  'await self.registration.unregister();',
  "for(const c of await self.clients.matchAll({type:'window'}))c.navigate(c.url);",
  '})()));',
].join('');

const listen = (cert, key) => `  listen 80;
  listen [::]:80;
  listen 443 ssl http2;
  listen [::]:443 ssl http2;
  ssl_certificate     ${cert};
  ssl_certificate_key ${key};`;

fs.writeFileSync('deploy/stopwatch-hosts.conf', `# Generated by scripts/make-migration.mjs from SITE_URL. Included inside the main server block.
server_name ${bare};
`);

const blocks = [`# Generated by scripts/make-migration.mjs (MIGRATION_REDIRECTS=${MIGRATION_REDIRECTS ? 'on' : 'off'}). Included at the top of deploy/nginx.conf.

# www.${bare} -> ${bare}, same path and query.
server {
${listen(CERT, KEY)}
  server_name www.${bare};
  return 301 ${SITE}$request_uri;
}
`];
if (MIGRATION_REDIRECTS) {
  blocks.push(`# The old host: every request 301s to the same path and query on ${SITE}, never the homepage.
server {
${listen(OLD_CERT, OLD_KEY)}
  server_name ${OLD_HOSTS.join(' ')};
  add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;

  # Installed users: a worker that clears the old caches, unregisters and reloads into the 301.
  location = /sw.js {
    default_type application/javascript;
    add_header Cache-Control "no-cache" always;
    return 200 "${killSw.replace(/"/g, '\\"')}";
  }

  location / {
    return 301 ${SITE}$request_uri;
  }
}
`);
}
else {
  blocks.push(`# The old host, until the switch: the same site, from its own block and certificate.
server {
${listen(OLD_CERT, OLD_KEY)}
  server_name ${OLD_HOSTS.join(' ')};
  include /etc/nginx/snippets/stopwatch-site.conf;
}
`);
}
fs.writeFileSync('deploy/stopwatch-old-host.conf', blocks.join('\n'));
console.log(`nginx hosts: ${bare} serves the site; ${OLD_HOSTS.join(', ')} ${MIGRATION_REDIRECTS ? `301 to ${SITE} (MIGRATION_REDIRECTS=on)` : 'serves it too (MIGRATION_REDIRECTS=off)'}; www.${bare} -> ${bare}`);
